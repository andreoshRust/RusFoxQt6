
function ДиагностикаМетодовКласса(диагОбъект) {
        
        русМетодыИзFunc = []
        англМетодыИзFunc = []
        карта = []
        
try {
            if (typeof диагОбъект.RusFunc === 'function') {
                jsonStr = диагОбъект.RusFunc()
                карта = JSON.parse(jsonStr)
                ВывестиСтрокуВКонсоль("✓ RusFunc() возвращает " + карта.length + " методов")
                ВывестиСтрокуВКонсоль("")
                
                
for (let i = 0; i <= карта.length - 1; i++) {
                    русМетодыИзFunc[русМетодыИзFunc.length] = карта[i].русскоеИмя
                    англМетодыИзFunc[англМетодыИзFunc.length] = карта[i].латинскоеИмя
}
            } else {
                ВывестиСтрокуВКонсоль("✗ Метод RusFunc() НЕ СУЩЕСТВУЕТ")
                return 
            };
} catch(e) {
            ВывестиСтрокуВКонсоль("✗ Ошибка при вызове RusFunc(): " + e)
            return 
}
        
        
        УстановитьЦветКонсоли("cyan")
        ВывестиСтрокуВКонсоль("═══════════════════════════════════════════════════════════════════════════════════════")
        ВывестиСтрокуВКонсоль("                   ПОЛНЫЙ СПИСОК МЕТОДОВ (русский ↔ английский)")
        ВывестиСтрокуВКонсоль("═══════════════════════════════════════════════════════════════════════════════════════")
        СброситьЦветКонсоли()
        
        
        максРусДлина = 0
        максАнглДлина = 0
for (let i = 0; i <= карта.length - 1; i++) {
            русское = карта[i].русскоеИмя
            латинское = карта[i].латинскоеИмя
            if (русское.length > максРусДлина) { максРусДлина = русское.length }
            if (латинское.length > максАнглДлина) { максАнглДлина = латинское.length }
}
        
        
        if (максРусДлина < 30) { максРусДлина = 30 }
        if (максАнглДлина < 30) { максАнглДлина = 30 }
        
        
        УстановитьЦветКонсоли("cyan")
        строкаЗаголовка = "┌─────┬" + "─".repeat(максРусДлина + 2) + "┬" + "─".repeat(максАнглДлина + 2) + "┐"
        ВывестиСтрокуВКонсоль(строкаЗаголовка)
        ВывестиСтрокуВКонсоль("│  №  │ Русский метод" + " ".repeat(максРусДлина - 13) + " │ Английский метод" + " ".repeat(максАнглДлина - 15) + " │")
        ВывестиСтрокуВКонсоль("├─────┼" + "─".repeat(максРусДлина + 2) + "┼" + "─".repeat(максАнглДлина + 2) + "┤")
        СброситьЦветКонсоли()
        
        
for (let i = 0; i <= карта.length - 1; i++) {
            русское = карта[i].русскоеИмя
            латинское = карта[i].латинскоеИмя
            
            
            русскоеВыровнено = русское
            if (русское.length < максРусДлина) {
                русскоеВыровнено = русское + " ".repeat(максРусДлина - русское.length)
            }
            
            латинскоеВыровнено = латинское
            if (латинское.length < максАнглДлина) {
                латинскоеВыровнено = латинское + " ".repeat(максАнглДлина - латинское.length)
            }
            
            
            доступен = typeof диагОбъект[латинское] === 'function'
            
            if (доступен) {
                УстановитьЦветКонсоли("green")
                ВывестиСтрокуВКонсоль("│ " + (i+1) + " │ " + русскоеВыровнено + " │ " + латинскоеВыровнено + " │")
                СброситьЦветКонсоли()
            } else {
                УстановитьЦветКонсоли("red")
                ВывестиСтрокуВКонсоль("│ " + (i+1) + " │ " + русскоеВыровнено + " │ " + латинскоеВыровнено + " │")
                СброситьЦветКонсоли()
            }
}
        
        
        УстановитьЦветКонсоли("cyan")
        ВывестиСтрокуВКонсоль("└─────┴" + "─".repeat(максРусДлина + 2) + "┴" + "─".repeat(максАнглДлина + 2) + "┘")
        СброситьЦветКонсоли()
        ВывестиСтрокуВКонсоль("")
        
        
        УстановитьЦветКонсоли("cyan")
        ВывестиСтрокуВКонсоль("═══════════════════════════════════════════════════════════════════════════════════════")
        ВывестиСтрокуВКонсоль("                          СТАТИСТИКА МЕТОДОВ")
        ВывестиСтрокуВКонсоль("═══════════════════════════════════════════════════════════════════════════════════════")
        СброситьЦветКонсоли()
        
        
        рабочиеАнгл = 0
        нерабочиеАнгл = []
        
for (let i = 0; i <= англМетодыИзFunc.length - 1; i++) {
            if (typeof диагОбъект[англМетодыИзFunc[i]] === 'function') {
                рабочиеАнгл = рабочиеАнгл + 1
            } else {
                нерабочиеАнгл[нерабочиеАнгл.length] = англМетодыИзFunc[i]
            }
}
        
        УстановитьЦветКонсоли("cyan")
        ВывестиСтрокуВКонсоль("  Всего методов в RusFunc: " + карта.length)
        ВывестиСтрокуВКонсоль("  Русских методов:         " + русМетодыИзFunc.length)
        ВывестиСтрокуВКонсоль("  Английских методов:       " + англМетодыИзFunc.length)
        СброситьЦветКонсоли()
        
        if (рабочиеАнгл == англМетодыИзFunc.length) {
            УстановитьЦветКонсоли("green")
            ВывестиСтрокуВКонсоль("  ✅ Доступно английских:    " + рабочиеАнгл + " из " + англМетодыИзFunc.length + " (ВСЕ ДОСТУПНЫ!)")
            СброситьЦветКонсоли()
        } else {
            УстановитьЦветКонсоли("red")
            ВывестиСтрокуВКонсоль("  ❌ Доступно английских:    " + рабочиеАнгл + " из " + англМетодыИзFunc.length)
            СброситьЦветКонсоли()
            
            if (нерабочиеАнгл.length > 0) {
                УстановитьЦветКонсоли("red")
                ВывестиСтрокуВКонсоль("  НЕДОСТУПНЫЕ английские методы:")
for (let i = 0; i <= нерабочиеАнгл.length - 1; i++) {
                    ВывестиСтрокуВКонсоль("    ✗ " + нерабочиеАнгл[i])
}
                СброситьЦветКонсоли()
            }
        }
        
        
        УстановитьЦветКонсоли("green")
        ВывестиСтрокуВКонсоль("  ✅ Русские методы:         " + русМетодыИзFunc.length + " (доступны через препроцессор)")
        СброситьЦветКонсоли()
        
        ВывестиСтрокуВКонсоль("")
        
   
    ВывестиСтрокуВКонсоль("=== КОНЕЦ ДИАГНОСТИКИ ===")
    ВывестиСтрокуВКонсоль("")
}
